import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { loadDotEnv, loadGroupConfig, pathsForConfig } from "./group-config.mjs";

export function workersDevEnabled(config) {
  const host = String(config?.publicHost || "").trim().toLowerCase();
  if (host === "workers.dev" || host.endsWith(".workers.dev")) return true;
  if (config?.workersDev === false) return false;
  return true;
}

export function renderWrangler(config, databaseId, extras = {}) {
  const access = config.access ?? {};
  const branding = config.branding ?? {};
  const document = {
    $schema: "./node_modules/wrangler/config-schema.json",
    name: config.workerName,
    main: "src/index.ts",
    // A custom domain makes Wrangler disable workers.dev unless this is set.
    // publicHost on workers.dev is the MCP URL, so that hostname stays on.
    workers_dev: workersDevEnabled(config),
    preview_urls: false,
    compatibility_date: "2026-10-09",
    compatibility_flags: ["nodejs_compat"],
    observability: {
      enabled: true,
      logs: { enabled: true, head_sampling_rate: 1 },
      traces: { enabled: true, head_sampling_rate: 0.1 },
    },
    vars: {
      BRAND_NAME: config.brandName,
      BRAND_ACCENT: branding.accent || "#7aa2ff",
      BRAND_LOGO: branding.logo || "",
      SEND_ALLOWLIST: config.sendAllowlist.join(","),
      SEND_POLICY: config.sendPolicy,
      INBOUND_RATE_LIMIT: String(config.inboundRateLimit ?? 20),
      SPAM_SCORE_THRESHOLD: config.spamScoreThreshold === "off" ? "off" : String(config.spamScoreThreshold ?? 4),
      INBOUND_BOT_RATE_LIMIT: String(config.inboundBotRateLimit ?? 30),
      INBOUND_AUTO_REPLY_LIMIT: String(config.inboundAutoReplyLimit ?? 20),
      INBOUND_AUTO_REPLY_WINDOW: String(config.inboundAutoReplyWindow ?? 3600),
      OUTBOUND_DAILY_STAMP_LIMIT: String(config.outboundDailyStampLimit ?? 200),
      CF_ACCESS_TEAM_DOMAIN: access.teamDomain || config.cfAccessTeamDomain || "",
      CF_ACCESS_AUD: extras.accessAud || access.aud || config.cfAccessAud || "",
      ACCESS_EMAIL_DOMAINS: (access.allowedEmailDomains || []).join(","),
      ADMIN_HOST: config.adminHost || "",
      PUBLIC_HOST: config.publicHost || "",
      WORKER_NAME: config.workerName,
      CF_ACCOUNT_ID: extras.accountId || config.accountId || "",
      UNIQUE_BOT_NAMES: config.uniqueBotNames === false ? "false" : "true",
      ...(config.routing === "literal" ? { ROUTING_MODE: "literal" } : {}),
      ...(config.outboundAllowlistOnly ? { OUTBOUND_ALLOWLIST_ONLY: "true" } : {}),
    },
    secrets: { required: ["ADMIN_API_KEY", "DATA_KEY", "MAIL_DOMAIN"] },
    d1_databases: [
      {
        binding: "DB",
        database_name: config.d1Name,
        database_id: databaseId,
        migrations_dir: "migrations",
      },
    ],
    kv_namespaces: [
      {
        binding: "OAUTH_KV",
        id: String(extras.oauthKvId || "00000000000000000000000000000000"),
      },
    ],
    r2_buckets: [{ binding: "MAIL_BUCKET", bucket_name: config.r2Bucket }],
    send_email: [{ name: "EMAIL" }],
    assets: {
      directory: "./dashboard/dist",
      binding: "ASSETS",
      run_worker_first: true,
      html_handling: "none",
      not_found_handling: "none",
    },
    triggers: { crons: ["*/15 * * * *"] },
  };
  const routes = [];
  if (config.adminHost) routes.push({ pattern: config.adminHost, custom_domain: true });
  // Literal installs use their own hostname for /mcp. Catch-all installs are unchanged.
  if (
    config.routing === "literal" &&
    config.publicHost &&
    !config.publicHost.endsWith(".workers.dev") &&
    config.publicHost !== config.adminHost
  ) {
    routes.push({ pattern: config.publicHost, custom_domain: true });
  }
  if (routes.length > 0) document.routes = routes;
  const routingNote = config.routing === "literal"
    ? `// No Email Routing addresses on purpose: setup writes literal rules for ${config.mailDomain} through the API and never changes the *@${config.mailZone} catch-all.`
    : `// No Email Routing addresses on purpose: setup owns the *@${config.mailZone} catch-all through the API, so Wrangler leaves routing alone.`;
  const note = [
    "// Generated by scripts/render-wrangler.mjs from the group config. Do not edit by hand.",
    routingNote,
    "// Declaring them here makes Wrangler flag that API-managed rule as a conflict and fail the deploy.",
    "",
  ].join("\n");
  return `${note}${JSON.stringify(document, null, 2)}\n`;
}

/**
 * AUD and account id for wrangler.jsonc. Setup and deploy both call this.
 * Audience: state `accessAud`, then `access.aud` on the group config.
 * Account id: state `accountId`, then the override (setup's account id, or CLOUDFLARE_ACCOUNT_ID on deploy).
 */
export function resolveInstallBindings(config, state = {}, overrides = {}) {
  const access = config?.access ?? {};
  const accessAud = String(state.accessAud || overrides.accessAud || access.aud || config?.cfAccessAud || "").trim();
  const accountId = String(state.accountId || overrides.accountId || config?.accountId || "").trim();
  const oauthKvId = String(state.oauthKvId || overrides.oauthKvId || "").trim();
  const extras = {};
  if (accessAud) extras.accessAud = accessAud;
  if (accountId) extras.accountId = accountId;
  if (oauthKvId) extras.oauthKvId = oauthKvId;
  return extras;
}

export function assertDeployAccessAud(extras, context = {}) {
  if (String(extras?.accessAud || "").trim()) return extras;
  const statePath = context.statePath || "the install state file";
  const configPath = context.configPath || "the group config";
  const worker = context.workerName ? ` ${context.workerName}` : "";
  throw new Error(
    `Refusing to deploy${worker}: CF_ACCESS_AUD is empty. Setup saves the Cloudflare Access audience as accessAud in ${statePath}. ` +
      `If that is missing, set access.aud in ${configPath}. ` +
      `An empty audience makes the admin dashboard return 401 after Access sign-in.`,
  );
}

export function readInstallState(statePath) {
  if (!statePath || !existsSync(statePath)) return {};
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(statePath, "utf8"));
  } catch (error) {
    throw new Error(`Could not parse ${statePath}: ${error instanceof Error ? error.message : "invalid JSON"}`);
  }
  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new Error(`${statePath} must be a JSON object`);
  }
  return parsed;
}

/** Rewrite wrangler.jsonc for deploy and for the migration step that runs just before it. */
export function writeDeployWrangler(configPath = process.env.BOT_MAIL_CONFIG || "bot-mail.config.json", options = {}) {
  const env = options.env ? { ...options.env } : { ...process.env };
  if (!options.env) loadDotEnv(".env", env);
  const statePath = options.statePath || pathsForConfig(configPath).statePath;
  const config = loadGroupConfig(configPath);
  const state = readInstallState(statePath);
  let databaseId = env.D1_DATABASE_ID || state.d1DatabaseId || "";
  if (!databaseId) databaseId = "00000000-0000-0000-0000-000000000000";
  const extras = resolveInstallBindings(config, state, { accountId: env.CLOUDFLARE_ACCOUNT_ID || "" });
  assertDeployAccessAud(extras, { statePath, configPath, workerName: config.workerName });
  const text = renderWrangler(config, databaseId, extras);
  writeFileSync(options.destination || "wrangler.jsonc", text);
  return {
    config,
    databaseId,
    extras,
    text,
    workerName: config.workerName,
    mailZone: config.mailZone,
    d1Name: config.d1Name,
  };
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invokedDirectly) {
  try {
    const written = writeDeployWrangler(process.env.BOT_MAIL_CONFIG || "bot-mail.config.json");
    process.stdout.write(`wrote wrangler.jsonc for ${written.workerName} (*@${written.mailZone})\n`);
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : "deploy config failed"}\n`);
    process.exit(1);
  }
}
